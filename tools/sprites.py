#!/usr/bin/env python3
"""Netgarden sprite pipeline: real photographs of plants, cut out, one per seasonal state.

Sprites live in assets/sprites/<plant-id>/<state>.png (RGBA, trimmed) and are listed in
assets/sprites/manifest.json with their credit and licence. States are:
  bare, spring, leaf, flower, fruit, autumn

Sources
  search  : Wikimedia Commons (CC BY / CC BY-SA / CC0 / public domain only)
  generate: an image model (OpenAI Images or Replicate), isolated-on-white prompts

Usage
  sprites.py search  <plant-id> [extra query words]      -> contact sheet to pick from
  sprites.py fetch   <plant-id> <state> "<File:...>"      -> download + record credit
  sprites.py cutout  <plant-id> <state> [--model u2net]   -> remove background, trim, add to manifest
  sprites.py import  <plant-id> <state> <image-file>      -> use your own photo, then cutout
  sprites.py generate <plant-id> <state> [--provider openai|replicate|local] [--quality low|medium|high]
      local = a diffusion model on this computer's CPU (pip install torch diffusers transformers accelerate);
      env LOCAL_MODEL (default stabilityai/sd-turbo), LOCAL_STEPS (4), LOCAL_SIZE (512)
  sprites.py generate-all [--provider openai] [--quality medium] [--limit N] [--only id1,id2]
  sprites.py prompts                                      -> print the generation prompt for every plant/state
  sprites.py list
"""
import io, json, os, re, sys, urllib.parse, urllib.request, base64

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPRITES = os.path.join(ROOT, 'assets', 'sprites')
RAW = os.path.join(SPRITES, '_raw')
MANIFEST = os.path.join(SPRITES, 'manifest.json')
UA = 'Netgarden/0.1 (open-source garden planner; https://github.com/stumacmar/Netgarden)'
OK_LICENSES = re.compile(r'^(CC0|CC BY(-SA)?( \d\.\d)?|Public domain|CC-BY(-SA)?.*)$', re.I)
STATES = ['bare', 'spring', 'leaf', 'flower', 'fruit', 'autumn']


def load_plants():
    """Read js/plants.js by evaluating it with node."""
    import subprocess
    js = "window={};require(process.argv[1]);console.log(JSON.stringify(window.PLANTS.all))"
    out = subprocess.check_output(['node', '-e', js, os.path.join(ROOT, 'js', 'plants.js')])
    return {p['id']: p for p in json.loads(out)}


def load_manifest():
    if os.path.exists(MANIFEST):
        with open(MANIFEST) as f: return json.load(f)
    return {}


def save_manifest(m):
    with open(MANIFEST, 'w') as f: json.dump(m, f, indent=1, sort_keys=True)
    # the app reads a script version so it also works when opened straight from a file
    with open(MANIFEST[:-5] + '.js', 'w') as f:
        f.write('/* generated by tools/sprites.py */\nwindow.SPRITE_MANIFEST = ' + json.dumps(m, sort_keys=True) + ';\n')


def http(url, binary=False):
    import time
    for attempt in range(6):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': UA})
            with urllib.request.urlopen(req, timeout=60) as r:
                data = r.read()
            time.sleep(0.4)  # be polite to Commons
            return data if binary else json.loads(data)
        except urllib.error.HTTPError as e:
            if e.code in (429, 503) and attempt < 5:
                time.sleep(3 * (attempt + 1)); continue
            raise


def commons_search(query, limit=12):
    q = urllib.parse.quote(query)
    url = (f'https://commons.wikimedia.org/w/api.php?action=query&generator=search&gsrsearch={q}'
           f'&gsrnamespace=6&gsrlimit={limit}&prop=imageinfo&iiprop=url|extmetadata|size|mime&iiurlwidth=400'
           f'&iiextmetadatafilter=LicenseShortName|Artist|Credit|ImageDescription&format=json')
    d = http(url)
    out = []
    for p in d.get('query', {}).get('pages', {}).values():
        ii = p['imageinfo'][0]
        if not ii.get('mime', '').startswith('image/'): continue
        em = ii.get('extmetadata', {})
        lic = em.get('LicenseShortName', {}).get('value', '')
        out.append({'title': p['title'], 'license': lic, 'ok': bool(OK_LICENSES.match(lic)),
                    'w': ii['width'], 'h': ii['height'], 'thumb': ii.get('thumburl'), 'url': ii['url'],
                    'artist': re.sub('<[^>]+>', '', em.get('Artist', {}).get('value', '')).strip(),
                    'desc': re.sub('<[^>]+>', '', em.get('ImageDescription', {}).get('value', ''))[:120]})
    return out


def cmd_search(pid, extra):
    from PIL import Image, ImageDraw
    plants = load_plants(); p = plants[pid]
    queries = [p['latin'] + ' ' + ' '.join(extra)] if extra else [p['latin'], p['name'], p['latin'] + ' habit']
    seen, results = set(), []
    for q in queries:
        for r in commons_search(q):
            if r['title'] in seen or not r['ok']: continue
            seen.add(r['title']); results.append(r)
    results = results[:24]
    os.makedirs(RAW, exist_ok=True)
    cols, cell = 6, 220
    rows = (len(results) + cols - 1) // cols
    sheet = Image.new('RGB', (cols * cell, max(1, rows) * (cell + 30)), 'white')
    draw = ImageDraw.Draw(sheet)
    for i, r in enumerate(results):
        try:
            im = Image.open(io.BytesIO(http(r['thumb'], True))).convert('RGB')
            im.thumbnail((cell - 10, cell - 10))
        except Exception as e:
            im = Image.new('RGB', (cell - 10, cell - 10), 'grey')
        x, y = (i % cols) * cell, (i // cols) * (cell + 30)
        sheet.paste(im, (x + 5, y + 5))
        draw.text((x + 5, y + cell), f'{i}: {r["w"]}x{r["h"]} {r["license"]}', fill='black')
    path = os.path.join(RAW, f'sheet-{pid}.png')
    sheet.save(path)
    with open(os.path.join(RAW, f'sheet-{pid}.json'), 'w') as f: json.dump(results, f, indent=1)
    print(path)
    for i, r in enumerate(results): print(i, r['title'], '|', r['license'], '|', r['desc'][:70])


def cmd_fetch(pid, state, title_or_index):
    assert state in STATES, f'state must be one of {STATES}'
    sheet = os.path.join(RAW, f'sheet-{pid}.json')
    rec = None
    if title_or_index.isdigit() and os.path.exists(sheet):
        rec = json.load(open(sheet))[int(title_or_index)]
    else:
        title = title_or_index if title_or_index.startswith('File:') else 'File:' + title_or_index
        q = urllib.parse.quote(title)
        d = http(f'https://commons.wikimedia.org/w/api.php?action=query&titles={q}&prop=imageinfo&iiprop=url|extmetadata|size&iiurlwidth=1600&iiextmetadatafilter=LicenseShortName|Artist&format=json')
        p = list(d['query']['pages'].values())[0]; ii = p['imageinfo'][0]; em = ii.get('extmetadata', {})
        lic = em.get('LicenseShortName', {}).get('value', '')
        rec = {'title': p['title'], 'license': lic, 'ok': bool(OK_LICENSES.match(lic)), 'url': ii['url'], 'thumb': ii.get('thumburl'),
               'artist': re.sub('<[^>]+>', '', em.get('Artist', {}).get('value', '')).strip(), 'w': ii['width'], 'h': ii['height']}
    if not rec['ok']: sys.exit(f'Licence {rec["license"]!r} is not reusable; pick another image.')
    # a 1600px version is plenty for a sprite
    big = re.sub(r'/\d+px-', '/1280px-', rec['thumb']) if rec.get('thumb') and max(rec['w'], rec['h']) > 1280 else rec['url']
    data = http(big, True)
    os.makedirs(os.path.join(RAW, pid), exist_ok=True)
    raw = os.path.join(RAW, pid, f'{state}.jpg')
    if os.path.exists(raw[:-4] + '.png'): os.remove(raw[:-4] + '.png')
    with open(raw, 'wb') as f: f.write(data)
    m = load_manifest(); m.setdefault(pid, {})[state] = {
        'source': 'https://commons.wikimedia.org/wiki/' + urllib.parse.quote(rec['title'].replace(' ', '_')),
        'credit': rec['artist'], 'license': rec['license'], 'file': None}
    save_manifest(m)
    print('saved', raw)


def cmd_import(pid, state, path):
    from PIL import Image
    os.makedirs(os.path.join(RAW, pid), exist_ok=True)
    raw = os.path.join(RAW, pid, f'{state}.jpg')
    Image.open(path).convert('RGB').save(raw, quality=92)
    m = load_manifest(); m.setdefault(pid, {})[state] = {'source': 'own photo', 'credit': '', 'license': 'own', 'file': None}
    save_manifest(m); print('saved', raw)


def key_white(im):
    """Cut a plant from a plain white studio background: alpha from distance to white, refined by u2net."""
    import numpy as np
    from PIL import Image
    a = np.asarray(im, dtype=np.float32)
    dist = 255 - a.min(axis=2)                      # how far from pure white the darkest channel is
    alpha = np.clip((dist - 10) * 4, 0, 255)        # soft key
    try:
        from rembg import remove, new_session
        global _U2NET
        try: _U2NET
        except NameError: _U2NET = new_session('u2net')
        m = remove(im, session=_U2NET, only_mask=True)
        mk = np.asarray(m.resize(im.size), dtype=np.float32)
        alpha = np.maximum(alpha * (mk / 255.0), np.where(mk > 200, alpha, 0))
    except Exception:
        pass
    out = im.convert('RGBA'); out.putalpha(Image.fromarray(alpha.astype('uint8')))
    return out


def remove_rmbg14(im):
    """Background removal with BRIA RMBG-1.4 (ONNX at ~/.u2net/rmbg14.onnx, CC BY-NC 4.0: personal use)."""
    import numpy as np, onnxruntime as ort
    from PIL import Image
    path = os.path.expanduser('~/.u2net/rmbg14.onnx')
    if not os.path.exists(path):
        http_bin = http('https://huggingface.co/briaai/RMBG-1.4/resolve/main/onnx/model.onnx', True)
        os.makedirs(os.path.dirname(path), exist_ok=True); open(path, 'wb').write(http_bin)
    sess = ort.InferenceSession(path, providers=['CPUExecutionProvider'])
    x = np.asarray(im.resize((1024, 1024), Image.BILINEAR), dtype=np.float32) / 255.0
    x = (x - 0.5) / 1.0
    x = x.transpose(2, 0, 1)[None]
    y = sess.run(None, {sess.get_inputs()[0].name: x})[0][0][0]
    y = (y - y.min()) / max(1e-6, (y.max() - y.min()))
    mask = Image.fromarray((y * 255).astype('uint8')).resize(im.size, Image.BILINEAR)
    out = im.convert('RGBA'); out.putalpha(mask)
    return out


def cmd_cutout(pid, state, model='u2net'):
    from PIL import Image, ImageFilter
    cands = [c for c in (os.path.join(RAW, pid, f'{state}.jpg'), os.path.join(RAW, pid, f'{state}.png')) if os.path.exists(c)]
    if not cands: sys.exit(f'No raw image for {pid} {state}: fetch, import or generate it first.')
    raw = max(cands, key=os.path.getmtime)  # newest wins
    im = Image.open(raw)
    im.thumbnail((1600, 1600))
    if im.mode == 'RGBA' and im.getchannel('A').getextrema()[0] < 128:
        out = im  # already has a transparent background (generated or lifted on a phone)
    elif model == 'white':
        out = key_white(im.convert('RGB'))
    elif model == 'rmbg14':
        im = im.convert('RGB')
        out = remove_rmbg14(im)
    else:
        from rembg import remove, new_session
        im = im.convert('RGB')
        session = new_session(model)
        out = remove(im, session=session, alpha_matting=False, post_process_mask=True)
    # soften the edge a touch and trim to content
    a = out.getchannel('A').filter(ImageFilter.GaussianBlur(0.6))
    out.putalpha(a)
    bbox = a.point(lambda v: 255 if v > 20 else 0).getbbox()
    if not bbox: sys.exit('Nothing left after background removal.')
    out = out.crop(bbox)
    if out.height > 1200: out = out.resize((round(out.width * 1200 / out.height), 1200), Image.LANCZOS)
    d = os.path.join(SPRITES, pid); os.makedirs(d, exist_ok=True)
    dest = os.path.join(d, f'{state}.png'); out.save(dest, optimize=True)
    m = load_manifest(); e = m.setdefault(pid, {}).setdefault(state, {'source': '', 'credit': '', 'license': ''})
    e.update({'file': f'assets/sprites/{pid}/{state}.png', 'w': out.width, 'h': out.height})
    save_manifest(m); print('wrote', dest, out.size)


def prompt_for(p, state):
    form = {'tree': 'mature tree', 'shrub': 'mature shrub', 'climber': 'climbing plant trained on a plain wooden trellis panel',
            'perennial': 'clump of herbaceous perennial', 'grass': 'clump of ornamental grass', 'bulb': 'small clump of bulbs'}[p['type']]
    what = {
        'bare': 'in midwinter, leafless, showing its bare branch structure' + (' with its coloured winter stems' if p.get('bare') else ''),
        'spring': 'in spring with fresh young foliage, no flowers',
        'leaf': 'in full summer leaf, no flowers',
        'flower': 'in full flower',
        'fruit': 'carrying ripe fruit',
        'autumn': 'in autumn colour',
    }[state]
    return (f'Photograph of a single {form} of {p["latin"]} ({p["name"]}), {what}, whole plant visible from ground level '
            f'at eye height, side view, isolated on a plain white background, soft natural daylight from the upper left, sharp focus, '
            f'no pot, no people, no text, photorealistic, botanical accuracy')


def states_for(p):
    s = ['leaf']
    if p.get('flower'): s.append('flower')
    if p.get('fruit'): s.append('fruit')
    if p.get('autumn') and p['type'] in ('tree', 'shrub', 'climber', 'grass'): s.append('autumn')
    if not p.get('ev') and p['type'] in ('tree', 'shrub', 'climber'): s.append('bare')
    return s


def cmd_prompts():
    for pid, p in load_plants().items():
        for st in states_for(p): print(f'{pid}\t{st}\t{prompt_for(p, st)}')


def cmd_generate(pid, state, provider='openai', quality='medium'):
    p = load_plants()[pid]; prompt = prompt_for(p, state)
    os.makedirs(os.path.join(RAW, pid), exist_ok=True)
    raw = os.path.join(RAW, pid, f'{state}.jpg')
    if provider == 'openai':
        key = os.environ.get('OPENAI_API_KEY') or sys.exit('Set OPENAI_API_KEY')
        body = json.dumps({'model': 'gpt-image-1', 'prompt': prompt, 'size': '1024x1536', 'quality': quality, 'n': 1,
                           'background': 'transparent', 'output_format': 'png'}).encode()
        req = urllib.request.Request(os.environ.get('OPENAI_BASE_URL', 'https://api.openai.com/v1') + '/images/generations', data=body,
                                     headers={'Authorization': 'Bearer ' + key, 'Content-Type': 'application/json', 'User-Agent': UA})
        with urllib.request.urlopen(req, timeout=300) as r: d = json.load(r)
        img = base64.b64decode(d['data'][0]['b64_json'])
    elif provider == 'replicate':
        key = os.environ.get('REPLICATE_API_TOKEN') or sys.exit('Set REPLICATE_API_TOKEN')
        body = json.dumps({'input': {'prompt': prompt, 'aspect_ratio': '2:3', 'output_format': 'jpg'}}).encode()
        req = urllib.request.Request('https://api.replicate.com/v1/models/black-forest-labs/flux-1.1-pro/predictions', data=body,
                                     headers={'Authorization': 'Bearer ' + key, 'Content-Type': 'application/json', 'Prefer': 'wait', 'User-Agent': UA})
        with urllib.request.urlopen(req, timeout=300) as r: d = json.load(r)
        out = d['output']; img = http(out if isinstance(out, str) else out[0], True)
    elif provider == 'local':
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import localgen
        os.makedirs(os.path.join(RAW, pid), exist_ok=True)
        tmp = os.path.join(RAW, pid, f'{state}.local.png')
        localgen.generate(prompt, tmp, os.environ.get('LOCAL_MODEL', 'stabilityai/sd-turbo'), int(os.environ.get('LOCAL_STEPS', '4')), int(os.environ.get('LOCAL_SIZE', '512')), seed=abs(hash(pid + state)) % 100000)
        img = open(tmp, 'rb').read(); os.remove(tmp)
    else:
        sys.exit('provider must be openai, replicate or local')
    from PIL import Image
    im = Image.open(io.BytesIO(img))
    for stale in (raw, raw[:-4] + '.png'):
        if os.path.exists(stale): os.remove(stale)
    if im.mode == 'RGBA':
        raw = raw[:-4] + '.png'; im.save(raw)
    else:
        im.convert('RGB').save(raw, quality=92)
    m = load_manifest(); m.setdefault(pid, {})[state] = {'source': f'generated ({provider})', 'credit': '', 'license': 'generated', 'file': None}
    save_manifest(m); print('saved', raw, '\nprompt:', prompt)


def cmd_generate_all(provider='openai', quality='medium', limit=None, only=None):
    plants = load_plants(); m = load_manifest(); todo = []
    for pid, p in plants.items():
        if only and pid not in only: continue
        for st in states_for(p):
            if not m.get(pid, {}).get(st, {}).get('file'): todo.append((pid, st))
    if limit: todo = todo[:int(limit)]
    print(f'{len(todo)} images to generate with {provider} at {quality} quality.')
    for i, (pid, st) in enumerate(todo):
        print(f'[{i + 1}/{len(todo)}] {pid} {st}')
        try:
            cmd_generate(pid, st, provider, quality); cmd_cutout(pid, st)
        except Exception as e:
            print('  failed:', e)


def cmd_list():
    m = load_manifest(); plants = load_plants()
    for pid in plants:
        have = [s for s, e in m.get(pid, {}).items() if e.get('file')]
        print(f'{pid:24s} {"".join("%-8s" % s for s in have) or "-"}')


if __name__ == '__main__':
    a = sys.argv[1:]
    if not a: sys.exit(__doc__)
    cmd = a[0]
    if cmd == 'search': cmd_search(a[1], a[2:])
    elif cmd == 'fetch': cmd_fetch(a[1], a[2], a[3])
    elif cmd == 'import': cmd_import(a[1], a[2], a[3])
    elif cmd == 'cutout': cmd_cutout(a[1], a[2], a[4] if len(a) > 4 and a[3] == '--model' else 'u2net')
    elif cmd == 'generate':
        opts = dict(zip(a[3::2], a[4::2]))
        cmd_generate(a[1], a[2], opts.get('--provider', 'openai'), opts.get('--quality', 'medium'))
    elif cmd == 'generate-all':
        opts = dict(zip(a[1::2], a[2::2]))
        cmd_generate_all(opts.get('--provider', 'openai'), opts.get('--quality', 'medium'), opts.get('--limit'), opts.get('--only', '').split(',') if opts.get('--only') else None)
    elif cmd == 'prompts': cmd_prompts()
    elif cmd == 'list': cmd_list()
    else: sys.exit(__doc__)
